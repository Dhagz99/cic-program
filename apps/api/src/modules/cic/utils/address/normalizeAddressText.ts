// utils/address/normalizeAddressText.ts

export const normalizeAddressText = (
    value?: string | null
 ) => {
 
    if (!value) {
       return "";
    }
 
    return value
 
       .toUpperCase()
 
       /*
       |--------------------------------------------------------------------------
       | FIX BROKEN CITY WORDS
       |--------------------------------------------------------------------------
       */
 
       .replace(/C\s*,\s*ITY/g, "CITY")
 
       .replace(/CI\s*,\s*TY/g, "CITY")
 
       .replace(/C\s+I\s+T\s+Y/g, "CITY")
 
       .replace(/CIT\s*Y/g, "CITY")
 
       /*
       |--------------------------------------------------------------------------
       | REMOVE DOTS
       |--------------------------------------------------------------------------
       */
 
       .replace(/[.]/g, "")
 
       /*
       |--------------------------------------------------------------------------
       | NORMALIZE DASHES
       |--------------------------------------------------------------------------
       */
 
       .replace(/-/g, " ")
 
       /*
       |--------------------------------------------------------------------------
       | COMMON ABBREVIATIONS
       |--------------------------------------------------------------------------
       */
 
       .replace(/\bST\b/g, "STREET")
 
       .replace(/\bBRGY\b/g, "BARANGAY")
 
       /*
       |--------------------------------------------------------------------------
       | REMOVE INVALID CHARS
       |--------------------------------------------------------------------------
       */
 
       .replace(/[^A-Z0-9,\s]/g, " ")
 
       /*
       |--------------------------------------------------------------------------
       | FIX COMMA SPACING
       |--------------------------------------------------------------------------
       */
 
       .replace(/\s*,\s*/g, ", ")
 
       /*
       |--------------------------------------------------------------------------
       | REMOVE MULTIPLE SPACES
       |--------------------------------------------------------------------------
       */
 
       .replace(/\s+/g, " ")
 
       /*
       |--------------------------------------------------------------------------
       | FINAL CLEAN
       |--------------------------------------------------------------------------
       */
 
       .trim();
 
 };